def get_builtin_templates() -> list[dict[str, Any]]:
    """获取所有内置模板的副本。"""
    return [dict(t) for t in BUILTIN_TEMPLATES]


def get_template_count_by_category() -> dict[str, int]:
    """统计各分类的模板数量。"""
    counts: dict[str, int] = {}
    for t in BUILTIN_TEMPLATES:
        cat = t["category"]
        counts[cat] = counts.get(cat, 0) + 1
    return counts
