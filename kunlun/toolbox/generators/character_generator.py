def _pick(lst: list[str], idx: int) -> str:
    return lst[idx % len(lst)]


def generate_character(request: CharacterGenerateRequest) -> CharacterResult:
    """
    生成完整人设。

    策略：
    1. 根据角色类型选择模板库
    2. 根据核心特质选择匹配度高的选项
    3. 自动生成姓名（如未指定）
    4. 组合为完整人设
    """
    templates = _ROLE_TEMPLATES[request.role_type]

    # 基于核心特质的简单哈希选择，确保相同输入产生相同输出
    seed = sum(ord(c) for c in request.core_trait + request.genre)

    # 姓名
    if request.name:
        name = request.name
    else:
        surname = _pick(_ANCIENT_SURNAMES, seed)
        if request.role_type == "antagonist":
            given = _pick(_ANCIENT_MALE_GIVEN, seed + 5)
        elif request.role_type == "supporting":
            given = _pick(_ANCIENT_FEMALE_GIVEN, seed + 3)
        else:
            given = _pick(_ANCIENT_MALE_GIVEN, seed)
        name = surname + given

    profile = CharacterProfile(
        name=name,
        age=_pick(templates["age"], seed),
        appearance=_pick(templates["appearance"], seed),
        background=_pick(templates["background"], seed + 1),
        personality=_pick(templates["personality"], seed + 2),
        motivation=_pick(templates["motivation"], seed + 3),
        ability=_pick(templates["ability"], seed + 4),
        growth_arc=_pick(templates["growth_arc"], seed + 5),
        classic_lines=[_pick(templates["classic_lines"], seed + i) for i in range(3)],
    )

    # 将核心特质注入性格描述
    if request.core_trait:
        profile.personality = f"核心特质：{request.core_trait}。{profile.personality}"

    return CharacterResult(character=profile)
